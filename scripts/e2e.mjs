import assert from 'node:assert/strict';
import { writeFile, mkdir } from 'node:fs/promises';
import { request, login, pauseForRateLimit } from './client.mjs';

const checks = [];
function passed(name) { checks.push(name); console.info(`PASS ${name}`); }
await pauseForRateLimit();
assert.equal((await request('/users')).status, 401);
passed('JWT required');
const token = await login();
const bobToken = await login('bob@example.test');
const users = await request('/users', { token });
assert.equal(users.status, 200);
assert.equal(users.data.id, 'user-1');
const orders = await request('/orders?userId=user-2', { token, headers: { 'x-user-id': 'user-2' } });
assert.equal(orders.status, 200);
assert.equal(orders.data.length, 2);
assert(orders.data.every(order => order.userId === 'user-1'));
passed('Routing and identity isolation');
const dashboard = await request('/dashboard', { token });
assert.equal(dashboard.status, 200);
assert.equal(dashboard.data.partial, false);
assert.equal(dashboard.data.user.id, 'user-1');
assert.equal(dashboard.data.orders.length, 2);
passed('Dashboard aggregation');
const upload = await request('/users/me/avatar/upload-url', { token, method: 'POST', body: { contentType: 'image/png' } });
assert.equal(upload.status, 201);
assert.equal(new URL(upload.data.uploadUrl).searchParams.get('X-Amz-Expires'), '300');
assert.equal(upload.data.expiresIn, 300);
await pauseForRateLimit();
const wrongUser = await request('/users/me/avatar/complete', { token: bobToken, method: 'POST', body: { objectKey: upload.data.objectKey } });
assert.equal(wrongUser.status, 400);
const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aZ1sAAAAASUVORK5CYII=', 'base64');
const put = await fetch(upload.data.uploadUrl, { method: 'PUT', body: png, headers: upload.data.headers, signal: AbortSignal.timeout(5000) });
assert.equal(put.status, 200);
assert.equal((await fetch(upload.data.uploadUrl, { signal: AbortSignal.timeout(5000) })).status, 403, 'PUT URL must not authorize GET');
const tamperedUrl = new URL(upload.data.uploadUrl);
tamperedUrl.pathname = tamperedUrl.pathname.replace('/user-1/', '/user-2/');
assert.equal((await fetch(tamperedUrl, { method: 'PUT', body: png, signal: AbortSignal.timeout(5000) })).status, 403, 'PUT URL must not authorize another object key');
const complete = await request('/users/me/avatar/complete', { token, method: 'POST', body: { objectKey: upload.data.objectKey } });
assert.equal(complete.status, 200);
const image = await fetch(complete.data.avatarUrl, { signal: AbortSignal.timeout(5000) });
assert.equal(image.status, 200);
assert.deepEqual(Buffer.from(await image.arrayBuffer()), png);
// Reusing the still-valid staging URL must never overwrite the approved avatar.
assert.equal((await fetch(upload.data.uploadUrl, { method: 'PUT', body: 'changed', signal: AbortSignal.timeout(5000) })).status, 200);
const approved = await fetch(complete.data.avatarUrl, { signal: AbortSignal.timeout(5000) });
assert.deepEqual(Buffer.from(await approved.arrayBuffer()), png);
passed('MinIO PUT capability: 300 seconds, one object, one operation, immutable approved avatar');
const invalidUpload = await request('/users/me/avatar/upload-url', { token, method: 'POST', body: { contentType: 'image/png' } });
assert.equal(invalidUpload.status, 201);
await fetch(invalidUpload.data.uploadUrl, { method: 'PUT', body: 'this is not an image', signal: AbortSignal.timeout(5000) });
const invalidComplete = await request('/users/me/avatar/complete', { token, method: 'POST', body: { objectKey: invalidUpload.data.objectKey } });
assert.equal(invalidComplete.status, 400);
passed('Invalid image rejected after upload');
const oversizeUpload = await request('/users/me/avatar/upload-url', { token, method: 'POST', body: { contentType: 'image/png' } });
assert.equal(oversizeUpload.status, 201);
const oversize = Buffer.alloc(5 * 1024 * 1024 + 1);
png.subarray(0, 8).copy(oversize);
assert.equal((await fetch(oversizeUpload.data.uploadUrl, { method: 'PUT', body: oversize, signal: AbortSignal.timeout(5000) })).status, 200);
const oversizeComplete = await request('/users/me/avatar/complete', { token, method: 'POST', body: { objectKey: oversizeUpload.data.objectKey } });
assert.equal(oversizeComplete.status, 400);
assert.equal(oversizeComplete.data.error, 'INVALID_IMAGE_SIZE');
passed('Avatar larger than 5 MiB rejected at completion');
await pauseForRateLimit();
const burst = await Promise.all(Array.from({ length: 11 }, () => request('/orders', { token })));
assert.equal(burst.filter(r => r.status === 200).length, 10);
assert.equal(burst.filter(r => r.status === 429).length, 1);
passed('Exactly 10 requests accepted in one second; request 11 gets 429');
await mkdir('reports', { recursive: true });
await writeFile('reports/e2e.json', JSON.stringify({ measuredAt: new Date().toISOString(), checks, result: 'passed' }, null, 2) + '\n');
console.info(`All ${checks.length} E2E checks passed. Report: reports/e2e.json`);
